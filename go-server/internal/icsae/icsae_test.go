// pyResult mirrors the summary emitted by dns-eval/Mappings/evaluate.py
// (tri-state, schema v9).
type pyResult struct {
        TotalControls    int      `json:"total_controls"`
        PassedCount      int      `json:"passed_count"`
        FailedCount      int      `json:"failed_count"`
        NACount          int      `json:"na_count"`
        NotMeasuredCount int      `json:"not_measured_count"`
        MeasuredControls int      `json:"measured_controls"`
        HighFailures     []string `json:"high_failures"`
        MediumFailures   []string `json:"medium_failures"`
        LowFailures      []string `json:"low_failures"`
        Passed           []string `json:"passed"`
        NotApplicable    []string `json:"not_applicable"`
        NotMeasured      []string `json:"not_measured"`
        Results          []struct {
                ID     string `json:"id"`
                Status string `json:"status"`
        } `json:"results"`
}

// TestCrossCheckPython proves the Go engine produces identical control verdicts to
// the canonical Python engine on the saved fixtures (testdata/*.input.json with
// testdata/*.expected.json generated by evaluate.py). Two engines, one catalog,
// must agree.
func TestCrossCheckPython(t *testing.T) {
        inputs, err := filepath.Glob(filepath.Join("testdata", "*.input.json"))
        if err != nil {
                t.Fatalf("glob testdata: %v", err)
        }
        if len(inputs) == 0 {
                t.Fatal("no testdata fixtures found")
        }

        for _, in := range inputs {
                base := strings.TrimSuffix(filepath.Base(in), ".input.json")
                t.Run(base, func(t *testing.T) {
                        rawIn, err := os.ReadFile(in)
                        if err != nil {
                                t.Fatalf("read input: %v", err)
                        }
                        var wrapper map[string]any
                        if err := json.Unmarshal(rawIn, &wrapper); err != nil {
                                t.Fatalf("parse input: %v", err)
                        }
                        fr, _ := wrapper["full_results"].(map[string]any)
                        if fr == nil {
                                t.Fatal("input missing full_results")
                        }

                        rawExp, err := os.ReadFile(filepath.Join("testdata", base+".expected.json"))
                        if err != nil {
                                t.Fatalf("read expected: %v", err)
                        }
                        var want pyResult
                        if err := json.Unmarshal(rawExp, &want); err != nil {
                                t.Fatalf("parse expected: %v", err)
                        }

                        got := Evaluate(fr)

                        if got.TotalControls != want.TotalControls ||
                                got.PassedCount != want.PassedCount ||
                                got.FailedCount != want.FailedCount ||
                                got.NACount != want.NACount ||
                                got.NotMeasuredCount != want.NotMeasuredCount ||
                                got.MeasuredControls != want.MeasuredControls {
                                t.Fatalf("count mismatch: got total=%d pass=%d fail=%d na=%d nm=%d measured=%d, want total=%d pass=%d fail=%d na=%d nm=%d measured=%d",
                                        got.TotalControls, got.PassedCount, got.FailedCount, got.NACount, got.NotMeasuredCount, got.MeasuredControls,
                                        want.TotalControls, want.PassedCount, want.FailedCount, want.NACount, want.NotMeasuredCount, want.MeasuredControls)
                        }

                        wantStatus := map[string]string{}
                        for _, r := range want.Results {
                                wantStatus[r.ID] = r.Status
                        }
                        for _, r := range got.Results {
                                if ws, ok := wantStatus[r.ID]; !ok {
                                        t.Errorf("control %s present in Go output but not Python", r.ID)
                                } else if ws != r.Status {
                                        t.Errorf("control %s: Go=%s Python=%s", r.ID, r.Status, ws)
                                }
                        }
                        if len(got.Results) != len(want.Results) {
                                t.Errorf("result count mismatch: Go=%d Python=%d", len(got.Results), len(want.Results))
                        }

                        assertSameSet(t, "high_failures", got.HighFailures, want.HighFailures)
                        assertSameSet(t, "medium_failures", got.MediumFailures, want.MediumFailures)
                        assertSameSet(t, "low_failures", got.LowFailures, want.LowFailures)
                        assertSameSet(t, "passed", got.Passed, want.Passed)
                        assertSameSet(t, "not_applicable", got.NotApplicable, want.NotApplicable)
                        assertSameSet(t, "not_measured", got.NotMeasured, want.NotMeasured)
                })
        }
}

func assertSameSet(t *testing.T, label string, got, want []string) {
        t.Helper()
        g := append([]string{}, got...)
        w := append([]string{}, want...)
        sort.Strings(g)
        sort.Strings(w)
        if strings.Join(g, ",") != strings.Join(w, ",") {
                t.Errorf("%s mismatch:\n  Go=%v\n  Python=%v", label, g, w)
        }
}

// TestHasNonEmptyListTypedSlices guards the Go-type vs JSON-type drift: live
// in-memory analyzer output uses concrete typed slices (e.g. []string), while
// JSON-round-tripped fixtures use []any. Both must be treated identically.
func TestHasNonEmptyListTypedSlices(t *testing.T) {
        cases := []struct {
                name string
                m    map[string]any
                want bool
        }{
                {"native []string non-empty", map[string]any{"records": []string{"a"}}, true},
                {"native []string empty", map[string]any{"records": []string{}}, false},
                {"json []any non-empty", map[string]any{"records": []any{"a"}}, true},
                {"json []any empty", map[string]any{"records": []any{}}, false},
                {"[]map[string]any non-empty", map[string]any{"records": []map[string]any{{"x": 1}}}, true},
                {"missing key", map[string]any{}, false},
                {"nil value", map[string]any{"records": nil}, false},
                {"wrong type (string)", map[string]any{"records": "abc"}, false},
        }
        for _, c := range cases {
                t.Run(c.name, func(t *testing.T) {
                        if got := hasNonEmptyList(c.m, "records"); got != c.want {
                                t.Errorf("hasNonEmptyList = %v, want %v", got, c.want)
                        }
                })
        }
}

